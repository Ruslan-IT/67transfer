    private function storePublicImage(string $fromPublic, string $to): string
    {
        $source = public_path($fromPublic);

        if (! is_file($source)) {
            return $fromPublic;
        }

        if (! Storage::disk('public')->exists($to)) {
            Storage::disk('public')->put($to, file_get_contents($source));
        }

        return $to;
    }
