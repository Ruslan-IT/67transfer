<p>Если в настройках включена Яндекс Метрика и человек разрешил аналитические cookie, браузер загружает счётчик Яндекса. До этого разрешения запрос к счётчику не выполняется. Google Maps может использоваться только как необязательные подсказки адреса. Без ключа Google форма принимает адрес, введённый вручную. Маркетинговые пиксели и рекламные теги на сайте не установлены. Включение маркетинговой категории в окне cookie само по себе ничего не загружает.</p>
