<p>Вместе с заявкой сохраняются факт отметки, дата и время, а также номер версии этого текста. Позднейшее изменение текста создаёт новую версию и не переписывает редакцию, которую человек уже принял. Лишний технический идентификатор, не нужный для этой связи, не собирается.</p>
<h2>Отзыв</h2>
<p>Согласие можно отозвать, написав оператору на контакты из блока реквизитов. Рассмотрение отзыва и проверка обращения остаются на стороне оператора.</p>
<p>Ознакомление с политикой обработки персональных данных является отдельным действием. Ссылка на политику рядом с чекбоксом не подменяет эту отметку.</p>
