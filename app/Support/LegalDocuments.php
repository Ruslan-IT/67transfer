<p>Отзыв направляется на email или телефон оператора из блока реквизитов. Отзыв не отменяет обработку, которая уже была законно завершена к моменту получения отзыва. Сайт не проверяет личность обратившегося автоматически: оператор делает это при рассмотрении обращения.</p>
