<p>При сборе персональных данных граждан Российской Федерации первичная запись, систематизация, накопление, хранение, уточнение и извлечение должны выполняться с использованием баз данных на территории РФ, статья 18 152-ФЗ. Сайт записывает заявку в подключённую базу и не проверяет автоматически, где эта база размещена. Размещение базы и почты, через которую проходит копия заявки, остаётся обязанностью оператора.</p>
