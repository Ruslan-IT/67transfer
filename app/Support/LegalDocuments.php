<p>По истечении заданного срока сервисная команда удаляет записи заявок. Текст версии согласия, который не содержит данных конкретного человека, сохраняется, чтобы ранее принятая редакция оставалась доступной для проверки. Если срок не задан, автоматического уничтожения нет.</p>
