<h2>Кто обрабатывает данные</h2>
<p>Оператор персональных данных указан в блоке реквизитов на странице политики и на этой странице. Если реквизиты не заполнены, они ещё не опубликованы. Шаблон не подставляет вымышленное имя, адрес или контакты.</p>
<h2>Какие данные и для чего</h2>
<p>Форма заказа трансфера: имя, телефон, адрес электронной почты, комментарий, данные маршрута, даты и времени, пассажиров, багажа, рейса и пожеланий. Цель — связаться с отправителем и организовать запрос перевозчику.</p>
<p>Форма вопроса: имя, email или телефон и текст вопроса. Цель — ответить на вопрос.</p>
<p>Форма запроса по направлению: email, места и дата. Цель — ответить на запрос информации о трансфере.</p>
